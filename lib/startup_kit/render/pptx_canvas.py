"""PPTX backend: editable shapes, native tables and native (data-editable) charts."""
from __future__ import annotations

from typing import Dict, List, Sequence

from lxml import etree
from pptx import Presentation
from pptx.chart.data import CategoryChartData
from pptx.dml.color import RGBColor
from pptx.enum.chart import XL_CHART_TYPE, XL_LEGEND_POSITION, XL_LABEL_POSITION
from pptx.enum.shapes import MSO_CONNECTOR, MSO_SHAPE
from pptx.enum.text import MSO_ANCHOR, MSO_AUTO_SIZE, PP_ALIGN
from pptx.oxml.ns import qn
from pptx.util import Emu, Inches, Pt

from .base import Canvas, ChartSpec, FitResult, TextStyle, fit_text, image_box, image_size, pptx_number_format


def _rgb(h: str) -> RGBColor:
    return RGBColor.from_string(h.lstrip("#").upper())


_ALIGN = {"left": PP_ALIGN.LEFT, "center": PP_ALIGN.CENTER, "right": PP_ALIGN.RIGHT}
_ANCHOR = {"top": MSO_ANCHOR.TOP, "middle": MSO_ANCHOR.MIDDLE, "bottom": MSO_ANCHOR.BOTTOM}


class PptxCanvas(Canvas):
    def __init__(self, width_in=13.333, height_in=7.5, title="", author="", subject=""):
        self.width, self.height = width_in, height_in
        self.prs = Presentation()
        self.prs.slide_width = Inches(width_in)
        self.prs.slide_height = Inches(height_in)
        cp = self.prs.core_properties
        cp.title, cp.author, cp.subject = title, author, subject
        cp.comments = "Generated by Startup Skills (startup-kit). Every figure should trace to the evidence appendix."
        self._blank = self.prs.slide_layouts[6]
        self.slide = None

    def begin(self, path):
        pass

    def new_page(self, background="#FFFFFF"):
        self.slide = self.prs.slides.add_slide(self._blank)
        bg = self.slide.background.fill
        bg.solid()
        bg.fore_color.rgb = _rgb(background)

    @staticmethod
    def _no_shadow(shape):
        # python-pptx shapes inherit theme effects; strip them for a flat, print-like look
        spPr = shape._element.spPr
        if spPr.find(qn("a:effectLst")) is None:
            spPr.append(etree.SubElement(spPr, qn("a:effectLst")))

    def rect(self, x, y, w, h, fill=None, line=None, line_w=0.75, radius=0.0):
        kind = MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE
        s = self.slide.shapes.add_shape(kind, Inches(x), Inches(y), Inches(max(w, 0.001)), Inches(max(h, 0.001)))
        if radius:
            s.adjustments[0] = min(0.5, radius / max(min(w, h), 0.01))
        if fill:
            s.fill.solid()
            s.fill.fore_color.rgb = _rgb(fill)
        else:
            s.fill.background()
        if line:
            s.line.color.rgb = _rgb(line)
            s.line.width = Pt(line_w)
        else:
            s.line.fill.background()
        self._no_shadow(s)
        s.text_frame.text = ""
        return s

    def ellipse(self, x, y, w, h, fill=None, line=None, line_w=0.75):
        s = self.slide.shapes.add_shape(MSO_SHAPE.OVAL, Inches(x), Inches(y), Inches(w), Inches(h))
        if fill:
            s.fill.solid()
            s.fill.fore_color.rgb = _rgb(fill)
        else:
            s.fill.background()
        if line:
            s.line.color.rgb = _rgb(line)
            s.line.width = Pt(line_w)
        else:
            s.line.fill.background()
        self._no_shadow(s)
        return s

    def line(self, x1, y1, x2, y2, color="#000000", width=0.75, dash=False, arrow=False):
        c = self.slide.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, Inches(x1), Inches(y1), Inches(x2), Inches(y2))
        c.line.color.rgb = _rgb(color)
        c.line.width = Pt(width)
        ln = c.line._get_or_add_ln()
        if dash:
            d = etree.SubElement(ln, qn("a:prstDash"))
            d.set("val", "dash")
        if arrow:
            t = etree.SubElement(ln, qn("a:tailEnd"))
            t.set("type", "triangle")
            t.set("w", "med")
            t.set("len", "med")
        return c

    def _style_run(self, run, style: TextStyle, size):
        f = run.font
        f.name = style.font
        f.size = Pt(size)
        f.bold = style.bold
        f.italic = style.italic
        f.color.rgb = _rgb(style.color)
        if style.tracking:
            run._r.get_or_add_rPr().set("spc", str(int(style.tracking * 100)))
        # also set East Asian / complex script font so Devanagari etc. fall back sensibly
        rPr = run._r.get_or_add_rPr()
        for tag in ("a:ea", "a:cs"):
            el = rPr.find(qn(tag))
            if el is None:
                el = etree.SubElement(rPr, qn(tag))
            el.set("typeface", style.font)

    def text(self, x, y, w, h, text, style: TextStyle, fit: FitResult = None):
        fit = fit or fit_text(text, style, w, h)
        tb = self.slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
        tf = tb.text_frame
        tf.word_wrap = True
        tf.auto_size = MSO_AUTO_SIZE.NONE
        tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
        tf.vertical_anchor = _ANCHOR[style.valign]
        t = text.upper() if style.caps else text
        for i, para in enumerate(t.split("\n")):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.alignment = _ALIGN[style.align]
            p.line_spacing = Pt(fit.size * style.leading)
            r = p.add_run()
            r.text = para
            self._style_run(r, style, fit.size)
        return tb

    def image(self, path, x, y, w, h, fit="contain"):
        iw, ih = image_size(path)
        bx, by, bw, bh = image_box(iw, ih, x, y, w, h, fit)
        return self.slide.shapes.add_picture(path, Inches(bx), Inches(by), Inches(bw), Inches(bh))

    def link(self, x, y, w, h, url):
        pass  # links are attached to text runs where needed

    def table(self, x, y, col_widths: Sequence[float], rows: List[List[str]], styles: Dict, row_heights):
        nr, nc = len(rows), len(col_widths)
        gf = self.slide.shapes.add_table(nr, nc, Inches(x), Inches(y), Inches(sum(col_widths)), Inches(sum(row_heights)))
        tbl = gf.table
        # remove the default banded theme style so our colours are the only styling
        tblPr = tbl._tbl.tblPr
        tblPr.set("firstRow", "0")
        tblPr.set("bandRow", "0")
        style_id = tblPr.find(qn("a:tableStyleId"))
        if style_id is None:
            style_id = etree.SubElement(tblPr, qn("a:tableStyleId"))
        style_id.text = "{5940675A-B579-460E-94D1-54222C63F5DA}"  # "No Style, Table Grid"
        for ci, cw in enumerate(col_widths):
            tbl.columns[ci].width = Inches(cw)
        hs: TextStyle = styles["header"]
        bs: TextStyle = styles["body"]
        first_col: TextStyle = styles.get("first_col", bs)
        pad = styles.get("pad", 0.08)
        rule = styles.get("rule", "#D9DDE1")
        for r, row in enumerate(rows):
            tbl.rows[r].height = Inches(row_heights[r])
            for ci in range(nc):
                cell = tbl.cell(r, ci)
                st = hs if r == 0 else (first_col if ci == 0 else bs)
                cs = styles.get("cell_styles", {}).get((r, ci))
                if cs:
                    st = st.with_(**cs)
                fill = styles.get("header_fill") if r == 0 else (styles.get("zebra") if (styles.get("zebra") and r % 2 == 0) else None)
                if fill:
                    cell.fill.solid()
                    cell.fill.fore_color.rgb = _rgb(fill)
                else:
                    cell.fill.background()
                cell.margin_left = cell.margin_right = Inches(pad)
                cell.margin_top = cell.margin_bottom = Inches(0.03)
                cell.vertical_anchor = MSO_ANCHOR.MIDDLE
                tf = cell.text_frame
                tf.word_wrap = True
                p = tf.paragraphs[0]
                p.alignment = _ALIGN[st.align]
                run = p.add_run()
                run.text = str(row[ci]) if ci < len(row) else ""
                self._style_run(run, st, st.size)
                self._cell_borders(cell, rule, bottom_w=1.2 if r == 0 else 0.5)
        return gf

    @staticmethod
    def _cell_borders(cell, color, bottom_w=0.5):
        tcPr = cell._tc.get_or_add_tcPr()
        for tag, w in (("a:lnL", 0), ("a:lnR", 0), ("a:lnT", 0), ("a:lnB", bottom_w)):
            ln = tcPr.find(qn(tag))
            if ln is None:
                ln = etree.SubElement(tcPr, qn(tag))
            if w:
                ln.set("w", str(int(Pt(w))))
                sf = etree.SubElement(ln, qn("a:solidFill"))
                c = etree.SubElement(sf, qn("a:srgbClr"))
                c.set("val", color.lstrip("#").upper())
            else:
                ln.set("w", "0")
                etree.SubElement(ln, qn("a:noFill"))

    def chart(self, x, y, w, h, spec: ChartSpec, theme):
        kinds = {"column": XL_CHART_TYPE.COLUMN_CLUSTERED, "bar": XL_CHART_TYPE.BAR_CLUSTERED,
                 "stacked-column": XL_CHART_TYPE.COLUMN_STACKED, "line": XL_CHART_TYPE.LINE_MARKERS}
        cd = CategoryChartData()
        cats = list(spec.categories)
        series = spec.series
        if spec.kind == "bar":  # PowerPoint draws bar categories bottom-up; reverse to match reading order
            cats = cats[::-1]
            series = [{**s, "values": list(s["values"])[::-1]} for s in series]
        cd.categories = cats
        for s in series:
            cd.add_series(s["name"], [v if v is not None else None for v in s["values"]])
        gf = self.slide.shapes.add_chart(kinds[spec.kind], Inches(x), Inches(y), Inches(w), Inches(h), cd)
        ch = gf.chart
        colors = spec.colors or theme.palette(max(len(spec.series), 1))
        ch.font.name = theme.body_font
        ch.font.size = Pt(9)
        ch.font.color.rgb = _rgb(theme.muted)
        legend = spec.show_legend if spec.show_legend is not None else len(spec.series) > 1
        ch.has_legend = legend
        if legend:
            ch.legend.position = XL_LEGEND_POSITION.TOP
            ch.legend.include_in_layout = False
        va = ch.value_axis
        va.visible = False
        va.has_major_gridlines = False
        va.has_minor_gridlines = False
        ca = ch.category_axis
        ca.has_major_gridlines = False
        ca.format.line.color.rgb = _rgb(theme.rule)
        ca.tick_labels.font.size = Pt(9)
        ca.tick_labels.font.color.rgb = _rgb(theme.muted)
        plot = ch.plots[0]
        if spec.kind in ("column", "bar", "stacked-column"):
            plot.gap_width = 50
            if spec.kind == "stacked-column":
                plot.overlap = 100
        nf = pptx_number_format(spec.number_format, spec.prefix, spec.suffix)
        for si, s in enumerate(plot.series):
            col = colors[si % len(colors)]
            if spec.kind == "line":
                s.format.line.color.rgb = _rgb(col)
                s.format.line.width = Pt(2)
                s.smooth = False
                s.marker.format.fill.solid()
                s.marker.format.fill.fore_color.rgb = _rgb(col)
                s.marker.format.line.color.rgb = _rgb(col)
            else:
                s.format.fill.solid()
                s.format.fill.fore_color.rgb = _rgb(col)
                if len(spec.series) == 1 and spec.highlight is not None:
                    n = len(spec.categories)
                    for i in range(n):
                        idx = (n - 1 - i) if spec.kind == "bar" else i
                        if i != spec.highlight:
                            pt = s.points[idx]
                            pt.format.fill.solid()
                            pt.format.fill.fore_color.rgb = _rgb(theme.rule)
        if spec.show_values and spec.kind != "stacked-column":
            plot.has_data_labels = True
            dl = plot.data_labels
            dl.number_format = nf
            dl.number_format_is_linked = False
            dl.font.size = Pt(9)
            dl.font.bold = True
            dl.font.color.rgb = _rgb(theme.ink)
            dl.position = XL_LABEL_POSITION.OUTSIDE_END if spec.kind != "line" else XL_LABEL_POSITION.ABOVE
        return gf

    def notes(self, text: str):
        if text:
            self.slide.notes_slide.notes_text_frame.text = text

    def save(self, path):
        self.prs.save(path)
